#!/usr/bin/env python3
"""Write a copy of the CPU training matrix with a seeded FinQA training cap (reduced plan; stdlib).

    cap_matrix.py configs/matrix-train-cpu.yaml configs/matrix-train-cpu.generated.yaml 2000
"""
import sys

OLD = "finqa: {n_train: null, class_balanced: false}"


def main(src, dst, cap):
    s = open(src).read()
    if OLD not in s:
        raise SystemExit("FinQA training line not found in " + src)
    s = s.replace(OLD, "finqa: {n_train: null, class_balanced: false, max_train_examples: %d}" % int(cap))
    with open(dst, "w") as fh:
        fh.write("# GENERATED by scripts/train-cpu/run_plan.sh from %s (FINQA_MAX_TRAIN=%s)\n" % (src, cap) + s)


if __name__ == "__main__":
    main(*sys.argv[1:4])
